import json, unicodedata
from janome.tokenizer import Tokenizer

T = Tokenizer()

def to_hira(s):
    out = []
    for ch in s:
        o = ord(ch)
        if 0x30A1 <= o <= 0x30F6:
            out.append(chr(o - 0x60))
        else:
            out.append(ch)
    return ''.join(out)

def reading(text):
    parts = []
    for tok in T.tokenize(text):
        r = tok.reading
        if not r or r == '*':
            parts.append(tok.surface)
        else:
            parts.append(to_hira(r))
    return ''.join(parts)

